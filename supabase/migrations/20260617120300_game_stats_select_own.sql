-- ============================================================================
--  SHARKY — Аналитика, фикс: SELECT-политика на game_stats (своя строка)
-- ----------------------------------------------------------------------------
--  Трекер dwell-времени теперь СНАЧАЛА вставляет строку «вида» (при загрузке),
--  а затем периодически её UPDATE-ит (active_ms растёт). Но UPDATE ... WHERE id=…
--  не может НАЙТИ строку без SELECT-видимости: у game_stats были только
--  insert/update-политики, без select → апдейт затрагивал 0 строк, и время
--  сессии не записывалось. Даём пользователю читать ТОЛЬКО свои строки.
--  Дашборд читает агрегаты через definer-RPC (минует RLS), так что чужая
--  статистика по-прежнему недоступна.
-- ============================================================================
drop policy if exists "select own stats" on public.game_stats;
create policy "select own stats" on public.game_stats
  for select to authenticated using (user_id = public.app_uid());

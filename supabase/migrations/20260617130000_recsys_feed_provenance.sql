-- ============================================================================
--  SHARKY — Рекомендации, слой 1: происхождение показа (feed provenance)
-- ----------------------------------------------------------------------------
--  Поведенческие сигналы уже собираются: dwell (game_stats.active_ms), loaded,
--  лайки/саймы/шеры/комменты. Их трогать не нужно. Для будущего ранжирования
--  не хватает того, что задним числом НЕ восстановить — как игра попала в показ:
--
--    feed_source   — какой алгоритм выбрал этот показ ('shuffle' сейчас,
--                    'reco_v1' и т.п. потом). Нужен для A/B и честной оценки
--                    «выдача vs рандом».
--    feed_position — на каком слоте ленты показали (0,1,2…). Нужен, чтобы
--                    отделить «игра хорошая» от «её просто поставили первой»
--                    (позиционный сдвиг: слот 0 всегда собирает больше dwell).
--
--  Аддитивно и безопасно: game_stats уже инсертится владельцем (RLS по
--  user_id = app_uid()), табличный GRANT покрывает новые колонки — в отличие от
--  users, где гранты колоночные. Колонки nullable, поэтому любой прочий путь
--  записи продолжит работать.
-- ============================================================================

alter table public.game_stats add column if not exists feed_source   text;
alter table public.game_stats add column if not exists feed_position smallint;

-- Для будущих выборок «показы конкретного алгоритма за период» и дебайаса
-- по позиции. created_at вторым ключом — окна по времени почти всегда нужны.
create index if not exists game_stats_feed_source_idx
  on public.game_stats(feed_source, created_at);
